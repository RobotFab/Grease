/**
 * docsPatcher.ts
 * ──────────────
 * Hover-documentation enrichment for the Arduino built-in API.
 *
 * Two jobs:
 *   1. buildClangdYaml(sidecarPath)
 *      Returns the `.clangd` YAML body that tells clangd to parse .ino as C++
 *      and force-include both Arduino.h and our hover-doc sidecar header.
 *
 *   2. patchInstalledCores({ log, arduinoCliPath })
 *      Walks every installed Arduino core (resolved via `arduino-cli config
 *      get directories.data`, so it works on macOS / Linux / Windows and for
 *      ESP32 users who never created an Arduino sketch folder) and adds
 *      Doxygen comments to Print.h / Stream.h / HardwareSerial.h. Idempotent:
 *      a marker comment at the top of each patched file makes re-runs no-ops.
 *      Cores whose header shape we don't recognize are skipped silently.
 *
 * Free functions only — C++ classes (Serial, Stream, Print, String) can't be
 * re-declared in a sidecar, so their hover docs live in the core headers.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { spawn } from "node:child_process";

const MARKER = "// arduino-grease:hover-docs:v1";

/**
 * Build the YAML body to drop at `<sketch>/.clangd`.
 *
 * The forward slashes are normalized so the same emitted YAML works on
 * Windows — clangd accepts forward slashes in include paths.
 */
export function buildClangdYaml(sidecarPath: string): string {
  const normalised = sidecarPath.replace(/\\/g, "/");
  const addFlags = normalised
    ? `[-xc++, -include, Arduino.h, -include, "${normalised}"]`
    : `[-xc++, -include, Arduino.h]`;
  return [
    "# Generated by Arduino Grease.",
    "# Tells clangd how to parse .ino files (they are not valid C++ on their own).",
    "CompileFlags:",
    `  Add: ${addFlags}`,
    "Index:",
    "  Background: Build",
    "",
  ].join("\n");
}

export interface WriteSketchClangdResult {
  wrote: boolean;
  path?: string;
  reason?: string;
}

/**
 * Write/refresh the `.clangd` file next to a sketch. Returns `wrote: false`
 * if the file is already up-to-date so callers can avoid noisy logs.
 */
export function writeSketchClangd(sketchDir: string, sidecarPath: string): WriteSketchClangdResult {
  if (!sketchDir) return { wrote: false, reason: "no sketchDir" };
  const target = path.join(sketchDir, ".clangd");
  const desired = buildClangdYaml(sidecarPath);
  try {
    if (fs.existsSync(target)) {
      const current = fs.readFileSync(target, "utf8");
      if (current === desired) return { wrote: false, reason: "up-to-date" };
    }
    fs.writeFileSync(target, desired, "utf8");
    return { wrote: true, path: target };
  } catch (e) {
    return { wrote: false, reason: e instanceof Error ? e.message : String(e) };
  }
}

/**
 * Locate the arduino-cli data dir. Tries `arduino-cli config get
 * directories.data` first (honors the user's actual config); falls back to
 * platform defaults if the CLI isn't on PATH.
 */
export function resolveArduinoDataDir(arduinoCliPath?: string): Promise<string | null> {
  return new Promise((resolve) => {
    const cli = arduinoCliPath || "arduino-cli";
    let stdout = "";
    let proc;
    try {
      proc = spawn(cli, ["config", "get", "directories.data"], { shell: false });
    } catch {
      resolve(null);
      return;
    }
    proc.stdout.on("data", (d) => { stdout += d.toString(); });
    proc.on("error", () => resolve(null));
    proc.on("close", () => {
      const trimmed = stdout.trim();
      if (trimmed) { resolve(trimmed); return; }
      const home = process.env.HOME || process.env.USERPROFILE || "";
      if (process.platform === "darwin") {
        resolve(path.join(home, "Library", "Arduino15"));
      } else if (process.platform === "win32") {
        const local = process.env.LOCALAPPDATA || path.join(home, "AppData", "Local");
        resolve(path.join(local, "Arduino15"));
      } else {
        resolve(path.join(home, ".arduino15"));
      }
    });
  });
}

interface PatchEdit {
  find: RegExp;
  replace: string;
}

interface Patch {
  name: string;
  signature: RegExp;
  edits: PatchEdit[];
}

