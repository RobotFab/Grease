const PATCHES: Patch[] = [PATCH_PRINT_CLASSIC, PATCH_STREAM_GENERIC, PATCH_HWSERIAL_AVR, PATCH_HWSERIAL_API];

interface ApplyResult {
  status: "patched" | "skipped" | "error";
  reason?: string;
  edits?: number;
}

export function applyPatchToFile(filePath: string, patch: Patch): ApplyResult {
  let content: string;
  try {
    content = fs.readFileSync(filePath, "utf8");
  } catch (e) {
    return { status: "error", reason: "read: " + (e instanceof Error ? e.message : String(e)) };
  }
  if (content.indexOf(MARKER) !== -1) return { status: "skipped", reason: "already patched" };
  if (!patch.signature.test(content)) return { status: "skipped", reason: "shape mismatch" };

  let next = content;
  let appliedCount = 0;
  for (const e of patch.edits) {
    if (e.find.test(next)) {
      next = next.replace(e.find, e.replace);
      appliedCount++;
    }
  }
  if (appliedCount === 0) return { status: "skipped", reason: "no edit anchors matched" };

  // Stamp the marker just after the first '*/' that closes the file's banner
  // comment. Falls back to file head if the file has no banner.
  if (/\*\//.test(next)) {
    next = next.replace(/\*\/\n/, "*/\n" + MARKER + "\n");
  } else {
    next = MARKER + "\n" + next;
  }

  try {
    fs.writeFileSync(filePath, next, "utf8");
    return { status: "patched", edits: appliedCount };
  } catch (e) {
    return { status: "error", reason: "write: " + (e instanceof Error ? e.message : String(e)) };
  }
}

export function findCoreHeaderFiles(dataDir: string): string[] {
  // <data>/packages/<vendor>/hardware/<arch>/<ver>/cores/<core>/{Print,Stream,HardwareSerial}.h
  // plus api/ subdir variant for modern ArduinoCore-API cores.
  const found: string[] = [];
  const packagesDir = path.join(dataDir, "packages");
  let vendors: string[];
  try { vendors = fs.readdirSync(packagesDir); } catch { return found; }
  for (const vendor of vendors) {
    const hwDir = path.join(packagesDir, vendor, "hardware");
    let archs: string[];
    try { archs = fs.readdirSync(hwDir); } catch { continue; }
    for (const arch of archs) {
      const archDir = path.join(hwDir, arch);
      let vers: string[];
      try { vers = fs.readdirSync(archDir); } catch { continue; }
      for (const ver of vers) {
        const coresDir = path.join(archDir, ver, "cores");
        let cores: string[];
        try { cores = fs.readdirSync(coresDir); } catch { continue; }
        for (const core of cores) {
          const coreDir = path.join(coresDir, core);
          for (const name of ["Print.h", "Stream.h", "HardwareSerial.h"]) {
            const direct = path.join(coreDir, name);
            const api = path.join(coreDir, "api", name);
            if (fs.existsSync(direct)) found.push(direct);
            if (fs.existsSync(api)) found.push(api);
          }
        }
      }
    }
  }
  return found;
}

export interface PatchCoresOptions {
  log?: (msg: string) => void;
  arduinoCliPath?: string;
}

export interface PatchCoresResult {
  patched: number;
  skipped: number;
  errors: number;
}

export async function patchInstalledCores(opts: PatchCoresOptions = {}): Promise<PatchCoresResult> {
  const log = opts.log || (() => {});
  const dataDir = await resolveArduinoDataDir(opts.arduinoCliPath);
  if (!dataDir) {
    log("[hover-docs] Could not resolve Arduino data dir; skipping core patches.");
    return { patched: 0, skipped: 0, errors: 0 };
  }
  log("[hover-docs] Scanning cores under " + dataDir);
  const files = findCoreHeaderFiles(dataDir);
  let patched = 0, skipped = 0, errors = 0;
  for (const file of files) {
    let result: ApplyResult = { status: "skipped", reason: "no matching patch" };
    for (const patch of PATCHES) {
      const r = applyPatchToFile(file, patch);
      if (r.status === "patched") { result = r; break; }
      if (r.status === "skipped" && r.reason === "already patched") { result = r; break; }
      result = r;
    }
    if (result.status === "patched") {
      patched++;
      log("[hover-docs] Patched " + file + " (" + result.edits + " edits)");
    } else if (result.status === "error") {
      errors++;
      log("[hover-docs] Error patching " + file + ": " + result.reason);
    } else {
      skipped++;
    }
  }
  log("[hover-docs] Done. Patched " + patched + ", skipped " + skipped + ", errors " + errors + ".");
  return { patched, skipped, errors };
}

